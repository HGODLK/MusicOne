/** 需要向模型明确时间时，从设备本地时钟生成；不放入稳定 system 前缀。 */
internal fun aiDeviceTimeContext(now: Calendar): String {
    val zone = now.timeZone
    val timestamp = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.ROOT).apply { timeZone = zone }.format(now.time)
    // 以该时刻的真实时区偏移计算，包含夏令时和非整点时区。
    val offsetMinutes = zone.getOffset(now.timeInMillis) / 60_000
    val absoluteMinutes = kotlin.math.abs(offsetMinutes)
    val offset = String.format(Locale.ROOT, "%s%02d:%02d", if (offsetMinutes < 0) "-" else "+",
        absoluteMinutes / 60, absoluteMinutes % 60)
    return "设备当前本地时间：$timestamp；时区：${zone.id}（UTC$offset）。这是本次请求时间，历史记录中的时间不代表当前时间。"
}
